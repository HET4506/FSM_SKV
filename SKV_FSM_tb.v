`timescale 1ns / 1ps

module SKV_FSM_tb();

reg clk;
reg reset;
reg din;

wire unlock;
wire [1:0] next_state;
wire [1:0] current_state;


// ============================================================
// DUT
// ============================================================

SKV_FSM dut (
    .clk(clk),
    .rst_n(reset),
    .din(din),
    .unlock(unlock),
    .next_state(next_state),
    .current_state(current_state)
);


// ============================================================
// CLOCK
// ============================================================

initial
    clk = 1'b0;

always #5 clk = ~clk;


// ============================================================
// APPLY ONE BIT
// Change input at negedge.
// DUT samples input at following posedge.
// ============================================================

task apply_bit;
    input bit_value;
    begin
        @(negedge clk);
        din = bit_value;

        @(posedge clk);
        #1;

        $display(
            "T=%0t | DIN=%b | CURRENT=%b | NEXT=%b | UNLOCK=%b",
            $time, din, current_state, next_state, unlock
        );
    end
endtask


// ============================================================
// RESET
// ============================================================

task reset_fsm;
    begin
        @(negedge clk);
        reset = 1'b0;
        din   = 1'b0;

        @(posedge clk);
        #1;

        $display(
            "T=%0t | RESET | CURRENT=%b | NEXT=%b | UNLOCK=%b",
            $time, current_state, next_state, unlock
        );

        @(negedge clk);
        reset = 1'b1;
    end
endtask


// ============================================================
// SEND A STRING OF BITS
// ============================================================

task send_sequence;
    input [31:0] sequence;
    input integer length;
    integer i;

    begin
        for(i = length-1; i >= 0; i = i-1)
            apply_bit(sequence[i]);
    end
endtask


// ============================================================
// MAIN TEST
// ============================================================

initial begin

    // --------------------------------------------------------
    // INITIALIZATION
    // --------------------------------------------------------

    reset = 1'b0;
    din   = 1'b0;

    // Initial reset
    @(posedge clk);
    #1;

    reset = 1'b1;

    $display("");
    $display("================================================");
    $display("STARTING FSM TESTBENCH");
    $display("================================================");
    $display("");


    // ========================================================
    // TEST 1
    // ALL 8 STATE / INPUT COMBINATIONS
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 1: ALL STATE/INPUT TRANSITIONS");
    $display("================================================");

    // 00 + 0 -> 00
    reset_fsm;
    apply_bit(0);

    // 00 + 1 -> 01
    reset_fsm;
    apply_bit(1);

    // 01 + 0 -> 10
    reset_fsm;
    apply_bit(1);
    apply_bit(0);

    // 01 + 1 -> 00
    reset_fsm;
    apply_bit(1);
    apply_bit(1);

    // 10 + 0 -> 00
    reset_fsm;
    apply_bit(1);
    apply_bit(0);
    apply_bit(0);

    // 10 + 1 -> 11
    reset_fsm;
    apply_bit(1);
    apply_bit(0);
    apply_bit(1);

    // 11 + 0 -> 00
    reset_fsm;
    apply_bit(1);
    apply_bit(0);
    apply_bit(1);
    apply_bit(0);

    // 11 + 1 -> 11
    reset_fsm;
    apply_bit(1);
    apply_bit(0);
    apply_bit(1);
    apply_bit(1);


    // ========================================================
    // TEST 2
    // BASIC DETECTION: 1011
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 2: 1011");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b1011, 4);


    // ========================================================
    // TEST 3
    // 101111111
    // UNLOCK MUST REMAIN HIGH
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 3: 101111111");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b101111111, 9);


    // ========================================================
    // TEST 4
    // 10110
    // DETECT THEN CLEAR
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 4: 10110");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b10110, 5);


    // ========================================================
    // TEST 5
    // 10111
    // UNLOCK STAYS HIGH
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 5: 10111");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b10111, 5);


    // ========================================================
    // TEST 6
    // 11011
    //
    // Contains 1011 starting at bit 2.
    // Tests continuous-stream behavior.
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 6: 11011");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b11011, 5);


    // ========================================================
    // TEST 7
    // 01011
    // Detection after leading zero.
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 7: 01011");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b01011, 5);


    // ========================================================
    // TEST 8
    // 00101100
    // Sequence in the middle of stream.
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 8: 00101100");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b00101100, 8);


    // ========================================================
    // TEST 9
    // NO DETECTION: 000000000
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 9: ALL ZEROS");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b000000000, 9);


    // ========================================================
    // TEST 10
    // NO DETECTION: 111111111
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 10: ALL ONES");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b111111111, 9);


    // ========================================================
    // TEST 11
    // MULTIPLE DETECTIONS
    //
    // 1011011
    //
    // First 1011 -> unlock
    // 0 -> clear
    // Second 1011 -> unlock
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 11: 1011011");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b1011011, 7);


    // ========================================================
    // TEST 12
    // 10111011
    //
    // Detection followed by 0,
    // then another possible sequence.
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 12: 10111011");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b10111011, 8);


    // ========================================================
    // TEST 13
    // REPEATED PATTERN
    //
    // 101110111011
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 13: REPEATED 1011 PATTERN");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b101110111011, 12);


    // ========================================================
    // TEST 14
    // SEQUENCE WITH MANY FALSE STARTS
    //
    // 1110101010111
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 14: FALSE STARTS");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b1110101010111, 13);


    // ========================================================
    // TEST 15
    // 10101010101011
    //
    // Long stream before detection.
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 15: LONG STREAM BEFORE DETECTION");
    $display("================================================");

    reset_fsm;

    send_sequence(32'b10101010101011, 14);


    // ========================================================
    // TEST 16
    // RESET WHILE IN STATE 01
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 16: RESET FROM STATE 01");
    $display("================================================");

    reset_fsm;

    apply_bit(1);

    // Current state should be 01
    reset_fsm;


    // ========================================================
    // TEST 17
    // RESET WHILE IN STATE 10
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 17: RESET FROM STATE 10");
    $display("================================================");

    reset_fsm;

    apply_bit(1);
    apply_bit(0);

    // Current state should be 10
    reset_fsm;


    // ========================================================
    // TEST 18
    // RESET WHILE IN STATE 11
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 18: RESET FROM STATE 11");
    $display("================================================");

    reset_fsm;

    apply_bit(1);
    apply_bit(0);
    apply_bit(1);

    // Current state should be 11
    reset_fsm;


    // ========================================================
    // TEST 19
    // LONG CONTINUOUS STREAM
    // ========================================================

    $display("");
    $display("================================================");
    $display("TEST 19: LONG CONTINUOUS STREAM");
    $display("================================================");

    reset_fsm;

    send_sequence(
        32'b11010011101011110101100101110111,
        32
    );


    // ========================================================
    // END
    // ========================================================

    $display("");
    $display("================================================");
    $display("FSM TESTBENCH COMPLETE");
    $display("================================================");

    #20;

    $finish;

end

endmodule